-- Code+ core schema: profiles, problems, hidden tests, submissions and storage.
-- Applied to the Supabase project as migration "codeplus_core_schema".

-- Profiles: one per auth user, created by trigger on sign-up.
create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  username text not null check (username ~ '^[A-Za-z0-9_]{3,20}$'),
  role text not null default 'user' check (role in ('user', 'admin')),
  created_at timestamptz not null default now()
);
create unique index profiles_username_lower_idx on public.profiles (lower(username));
alter table public.profiles enable row level security;

create policy "Signed-in users can read profiles"
  on public.profiles for select to authenticated using (true);
create policy "Users can rename themselves"
  on public.profiles for update to authenticated
  using ((select auth.uid()) = id) with check ((select auth.uid()) = id);

-- Users may only change their username, never their role.
revoke insert, update, delete on public.profiles from anon, authenticated;
grant update (username) on public.profiles to authenticated;

create function public.is_admin()
returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and role = 'admin'
  );
$$;
revoke execute on function public.is_admin() from public, anon;
grant execute on function public.is_admin() to authenticated;

create function public.username_available(name text)
returns boolean
language sql stable security definer set search_path = ''
as $$
  select not exists (select 1 from public.profiles where lower(username) = lower(name));
$$;
grant execute on function public.username_available(text) to anon, authenticated;

create function public.handle_new_user()
returns trigger
language plpgsql security definer set search_path = ''
as $$
declare
  base text;
  candidate text;
  n integer := 0;
begin
  base := coalesce(
    nullif(regexp_replace(coalesce(new.raw_user_meta_data ->> 'username', ''), '[^A-Za-z0-9_]', '', 'g'), ''),
    nullif(regexp_replace(coalesce(new.raw_user_meta_data ->> 'user_name', new.raw_user_meta_data ->> 'preferred_username', ''), '[^A-Za-z0-9_]', '', 'g'), ''),
    nullif(regexp_replace(split_part(coalesce(new.email, ''), '@', 1), '[^A-Za-z0-9_]', '', 'g'), ''),
    'coder'
  );
  base := rpad(left(base, 16), 3, '0');
  candidate := base;
  while exists (select 1 from public.profiles where lower(username) = lower(candidate)) loop
    n := n + 1;
    candidate := left(base, 16) || n::text;
  end loop;
  insert into public.profiles (id, username) values (new.id, candidate);
  return new;
end;
$$;
revoke execute on function public.handle_new_user() from public, anon, authenticated;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Problems created by admins. Built-in problems live in the frontend (ids below 1000).
create table public.problems (
  id integer generated by default as identity (start with 1001) primary key,
  title text not null check (char_length(title) between 3 and 80),
  difficulty text not null check (difficulty in ('Easy', 'Medium', 'Hard')),
  tags text[] not null default '{}',
  summary text not null default '' check (char_length(summary) <= 200),
  statement text not null check (char_length(statement) between 1 and 20000),
  input_spec text not null default '',
  output_spec text not null default '',
  constraints text[] not null default '{}',
  hint text,
  samples jsonb not null default '[]'::jsonb check (jsonb_typeof(samples) = 'array'),
  time_limit_ms integer not null default 1000 check (time_limit_ms between 100 and 10000),
  memory_mb integer not null default 256 check (memory_mb between 16 and 1024),
  output_mb integer not null default 16 check (output_mb between 1 and 64),
  hidden_tests integer not null default 0 check (hidden_tests between 0 and 200),
  published boolean not null default true,
  created_by uuid default auth.uid() references public.profiles (id) on delete set null,
  created_at timestamptz not null default now()
);
create index problems_created_by_idx on public.problems (created_by);
alter table public.problems enable row level security;

create policy "Signed-in users read published problems"
  on public.problems for select to authenticated
  using (published or (select public.is_admin()));
create policy "Admins create problems"
  on public.problems for insert to authenticated
  with check ((select public.is_admin()));
create policy "Admins update problems"
  on public.problems for update to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));
create policy "Admins delete problems"
  on public.problems for delete to authenticated
  using ((select public.is_admin()));

-- Hidden test files for a problem, stored in the private "testcases" bucket.
create table public.problem_tests (
  problem_id integer not null references public.problems (id) on delete cascade,
  idx integer not null check (idx >= 1),
  input_path text not null,
  output_path text not null,
  input_bytes integer not null default 0,
  output_bytes integer not null default 0,
  primary key (problem_id, idx)
);
alter table public.problem_tests enable row level security;

create policy "Admins read tests" on public.problem_tests for select to authenticated using ((select public.is_admin()));
create policy "Admins add tests" on public.problem_tests for insert to authenticated with check ((select public.is_admin()));
create policy "Admins change tests" on public.problem_tests for update to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));
create policy "Admins remove tests" on public.problem_tests for delete to authenticated using ((select public.is_admin()));

-- Submissions: each user sees and creates only their own.
create table public.submissions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references public.profiles (id) on delete cascade,
  problem_id integer not null,
  language text not null check (language in ('cpp', 'c', 'py')),
  verdict text not null check (verdict in ('AC', 'WA', 'TLE', 'MLE', 'RE', 'SV', 'OLE', 'CE', 'IE')),
  cpu_ms real not null default 0,
  memory_kb integer not null default 0,
  failed_test integer,
  source text not null default '' check (octet_length(source) <= 65536),
  file_path text,
  created_at timestamptz not null default now()
);
create index submissions_user_created_idx on public.submissions (user_id, created_at desc);
alter table public.submissions enable row level security;

create policy "Users read their submissions"
  on public.submissions for select to authenticated
  using ((select auth.uid()) = user_id);
create policy "Users create their submissions"
  on public.submissions for insert to authenticated
  with check ((select auth.uid()) = user_id);

-- Storage: solution files (per user folder) and test cases (admins only).
insert into storage.buckets (id, name, public, file_size_limit)
values ('solutions', 'solutions', false, 65536),
       ('testcases', 'testcases', false, 52428800)
on conflict (id) do nothing;

create policy "Users upload their own solution files"
  on storage.objects for insert to authenticated
  with check (bucket_id = 'solutions' and (storage.foldername(name))[1] = (select auth.uid())::text);
create policy "Users read their own solution files"
  on storage.objects for select to authenticated
  using (bucket_id = 'solutions' and (storage.foldername(name))[1] = (select auth.uid())::text);

create policy "Admins upload test files"
  on storage.objects for insert to authenticated
  with check (bucket_id = 'testcases' and (select public.is_admin()));
create policy "Admins read test files"
  on storage.objects for select to authenticated
  using (bucket_id = 'testcases' and (select public.is_admin()));
create policy "Admins replace test files"
  on storage.objects for update to authenticated
  using (bucket_id = 'testcases' and (select public.is_admin()));
create policy "Admins delete test files"
  on storage.objects for delete to authenticated
  using (bucket_id = 'testcases' and (select public.is_admin()));
