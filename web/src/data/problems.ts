export function getProblem(id: number): Problem | undefined {
  return PROBLEMS.find((p) => p.id === id);
}

export function neighbours(id: number): { prev?: Problem; next?: Problem } {
  const i = PROBLEMS.findIndex((p) => p.id === id);
  return { prev: PROBLEMS[i - 1], next: PROBLEMS[i + 1] };
}

/** One problem per UTC day, rotating through the catalog. */
export function dailyProblem(now = Date.now()): Problem {
  const day = Math.floor(now / 86_400_000);
  return PROBLEMS[day % PROBLEMS.length];
}
